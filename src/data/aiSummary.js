export function generateAiSummary(answers) {
  const objectText = {
    Квартира: "для квартиры важно сохранить баланс между уютом, функциональностью и визуальной чистотой",
    Дом: "для дома важно собрать цельный сценарий жизни: общие зоны, приватность, свет и материалы",
    Коммерция: "для коммерческого пространства особенно важны первое впечатление, навигация и ощущение доверия",
    Офис: "для офиса важно совместить статус, концентрацию команды и комфортную рабочую среду",
  };

  const priorityText = {
    Практичность:
      "акцент стоит сделать на понятной планировке, долговечных материалах и контролируемой реализации",
    Эстетика:
      "главный фокус — визуальная цельность, свет, пропорции и эмоциональное впечатление",
    Статус:
      "лучше раскрывать проект через премиальные материалы, выразительные детали и сильную подачу",
    "Под вас":
      "сценарий стоит строить вокруг привычек, ритма жизни и индивидуальных задач",
  };

  const moodText = {
    "Тёплый минимализм":
      "подойдут натуральные фактуры, мягкий рассеянный свет, дерево, текстиль и спокойная тёплая палитра",
    "Глубокий контраст":
      "подойдут графитовые оттенки, камень, металл, акцентный свет и более драматичная атмосфера",
    "Современная классика":
      "подойдут спокойные благородные оттенки, мрамор, латунь, молдинги и мягкая симметрия",
    "Мягкий модерн":
      "подойдут светлые поверхности, плавные формы, архитектурная подсветка и воздушная композиция",
  };

  const levelText = {
    Комфорт:
      "формат можно держать в рациональном бюджете без потери ощущения продуманного пространства",
    Бизнес:
      "лучше выбрать баланс между эстетикой, сроками, комплектацией и качеством реализации",
    Премиум:
      "стоит заложить более глубокую детализацию, комплектацию и авторский контроль решений",
    "Под вас":
      "формат лучше определить после уточнения площади, бюджета, сроков и сценария использования",
  };

  return {
    title: "Предварительный вывод",
    text: `${objectText[answers.object] || "для проекта важно собрать цельную систему решений"}. ${
      priorityText[answers.priority] || "важно определить главный приоритет проекта"
    }. ${moodText[answers.mood] || "атмосфера будет уточняться после разбора вводных"}. ${
      levelText[answers.level] || "формат реализации лучше определить после консультации"
    }.`,
    bullets: [
      getLightAdvice(answers.mood),
      getMaterialAdvice(answers.mood),
      getProcessAdvice(answers.priority),
    ],
  };
}

function getLightAdvice(mood) {
  if (mood === "Глубокий контраст") return "Свет: акцентный, направленный, с глубокими тенями.";
  if (mood === "Современная классика") return "Свет: мягкий, декоративный, с ощущением статуса.";
  if (mood === "Мягкий модерн") return "Свет: воздушный, архитектурный, без визуального шума.";
  return "Свет: тёплый, рассеянный, комфортный для жизни.";
}

function getMaterialAdvice(mood) {
  if (mood === "Глубокий контраст") return "Материалы: камень, графит, металл, плотные фактуры.";
  if (mood === "Современная классика") return "Материалы: мрамор, латунь, дерево, спокойные оттенки.";
  if (mood === "Мягкий модерн") return "Материалы: микроцемент, стекло, светлое дерево, текстиль.";
  return "Материалы: дерево, текстиль, керамика, натуральные поверхности.";
}

function getProcessAdvice(priority) {
  if (priority === "Практичность") return "Процесс: начать со сметы, сроков и понятного плана реализации.";
  if (priority === "Эстетика") return "Процесс: сначала собрать визуальную концепцию и сценарии света.";
  if (priority === "Статус") return "Процесс: заранее заложить комплектацию и детализацию материалов.";
  return "Процесс: начать с интервью по привычкам, задачам и образу жизни.";
}